  // ---------- 숫자 바꾸기 ----------
  function rng(seed) {
    let a = seed >>> 0;
    return () => {
      a = (a + 0x6d2b79f5) >>> 0;
      let t = a;
      t = Math.imul(t ^ (t >>> 15), t | 1);
      t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }
  // seed 0 = 원래 숫자. 그 외 = 데이터 숫자와 {변수}를 무작위로.
  function instantiate(p, seed = 0) {
    const R = rng(seed);
    const vars = Object.fromEntries(Object.entries(p.params || {}).map(([k, list]) => [k, seed ? list[Math.floor(R() * list.length)] : list[0]]));
    const sub = (s) => String(s).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
    const ds = DATA[p.data];
    const grid = { ...ds.cells };
    if (seed) {
      for (const { range, min, max, step = 1 } of ds.rand) {
        for (const ref of E.cellsOf(range).flat()) grid[ref] = String(min + step * Math.floor(R() * ((max - min) / step + 1)));
      }
    }
    for (const [k, v] of Object.entries(p.cells || {})) grid[k] = sub(v);
    if (p.head) grid[E.shift(p.target, -1)] = p.head;
    return { ...p, template: p, seed, grid, q: sub(p.q), answer: sub(p.answer) };
  }

